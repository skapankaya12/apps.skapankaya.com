// Turns the welcome email mockup into the template the site actually sends.
//
//   node design/emails/build-template.mjs
//
// welcome.html in this folder stays the one place the email is designed and
// previewed (the "emailpreview" server in .claude/launch.json). This writes
// lib/emails/sellerWelcome.ts from it: comments stripped, whitespace between
// tags collapsed, and every img/ path swapped for a {{IMG}} placeholder that
// the sender fills with the site's own /email/ folder. Re-run after any edit
// to welcome.html, or the site keeps sending the old design.

import { readFile, writeFile, mkdir } from "node:fs/promises";

const here = new URL(".", import.meta.url);
const src = await readFile(new URL("welcome.html", here), "utf8");

const html = src
  .replace(/<!--[\s\S]*?-->/g, "")
  .replace(/src="img\//g, 'src="{{IMG}}')
  // Only whitespace that spans a line break: a plain space between two tags is
  // real (the gaps in the per-letter gradient words are exactly that).
  .replace(/>\s*\n\s*</g, "><")
  .replace(/\n\s*/g, " ")
  .trim();

if (html.includes('src="img/')) throw new Error("an img/ path survived");
if (html.length > 90_000) {
  // Gmail clips anything over about 102KB and hides the rest behind a link.
  throw new Error(`template is ${html.length} bytes, too close to Gmail's clip`);
}

const out = `// GENERATED by design/emails/build-template.mjs from design/emails/welcome.html.
// Do not edit by hand: change welcome.html and re-run the script.

/** The seller welcome email. {{IMG}} is replaced with the public /email/ URL. */
export const SELLER_WELCOME_HTML = ${JSON.stringify(html)};
`;

await mkdir(new URL("../../lib/emails/", here), { recursive: true });
await writeFile(new URL("../../lib/emails/sellerWelcome.ts", here), out);
console.log(`lib/emails/sellerWelcome.ts written, ${html.length} bytes of HTML`);
