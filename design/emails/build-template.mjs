// Turns the email mockups into the templates the site actually sends.
//
//   node design/emails/build-template.mjs
//
// The .html files in this folder stay the one place each email is designed and
// previewed (the "emailpreview" server in .claude/launch.json). This writes a
// lib/emails/*.ts module from each: comments stripped, line breaks between tags
// collapsed, and every img/ path swapped for a {{IMG}} placeholder that the
// sender fills with the site's own /email/ folder. Any other {{PLACEHOLDER}}
// (e.g. {{UNSUBSCRIBE}}) is left for the sender to fill per person. Re-run
// after any edit to an .html file, or the site keeps sending the old design.

import { readFile, writeFile, mkdir } from "node:fs/promises";

const EMAILS = [
  { html: "welcome.html", ts: "sellerWelcome.ts", name: "SELLER_WELCOME_HTML", about: "The seller welcome email." },
  { html: "no-listing.html", ts: "sellerNoListing.ts", name: "SELLER_NO_LISTING_HTML", about: "The nudge to a seller with no listing three days in." },
];

const here = new URL(".", import.meta.url);
await mkdir(new URL("../../lib/emails/", here), { recursive: true });

for (const e of EMAILS) {
  const src = await readFile(new URL(e.html, here), "utf8");
  const html = src
    .replace(/<!--[\s\S]*?-->/g, "")
    .replace(/src="img\//g, 'src="{{IMG}}')
    // Only whitespace that spans a line break: a plain space between two tags is
    // real (the gaps in the per-letter gradient words are exactly that).
    .replace(/>\s*\n\s*</g, "><")
    .replace(/\n\s*/g, " ")
    .trim();

  if (html.includes('src="img/')) throw new Error(`${e.html}: an img/ path survived`);
  if (html.length > 90_000) {
    // Gmail clips anything over about 102KB and hides the rest behind a link.
    throw new Error(`${e.html} is ${html.length} bytes, too close to Gmail's clip`);
  }

  const out = `// GENERATED by design/emails/build-template.mjs from design/emails/${e.html}.
// Do not edit by hand: change the .html file and re-run the script.

/** ${e.about} {{IMG}} is replaced with the public /email/ URL. */
export const ${e.name} = ${JSON.stringify(html)};
`;
  await writeFile(new URL(`../../lib/emails/${e.ts}`, here), out);
  console.log(`lib/emails/${e.ts} written, ${html.length} bytes of HTML`);
}
